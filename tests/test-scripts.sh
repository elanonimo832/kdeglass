# The effect's scripts: few, clear, self-sufficient, and without the id that broke rendering.
EF="$PROJECT/effect-kwin"

echo "  -- only the essential scripts --"
# Nine debug scripts were scaffolding for the bisection; their value (the variant
# table) is in INCIDENT.md. FIVE remain, each with a purpose that is still true:
#   build.sh            builds and verifies the paint chain
#   install.sh          installs and activates (needs sudo)
#   verify-chain.sh     the check that prevents the black screen
#   test-glass.sh       live test: the band follows the background
#   test-titlebar.sh    live test: the title bar only, read from KWin's geometry
#   tune.sh             sets the live settings and applies them in ONE call
# The four that were retired to tests/archive/ had stopped being able to say anything:
# test-installed.sh looked for M1.1's flat marker, test-hot.sh and calibrate.sh waited
# for CALIB lines the effect no longer emits, and test-diffusion.sh measured M1.2's band
# diffusion, which the design no longer claims. A live script whose verdict is
# meaningless is worse than no script: it teaches the reader to ignore verdicts.
expected="build.sh capture-pair.sh install.sh test-titlebar.sh test-glass.sh tune.sh verify-chain.sh"
for s in $expected; do afirmar_existe "existe $s" "$EF/$s"; done

n=$(ls "$EF"/*.sh 2>/dev/null | wc -l)
afirmar_igual "number of scripts (no scaffolding)" "7" "$n"
extra=""
for x in "$EF"/*.sh; do
  [ -f "$x" ] || continue
  b="$(basename "$x")"
  case " $expected " in *" $b "*) ;; *) extra="$extra $b";; esac
done
afirmar_igual "no script is left over" "" "$extra"

echo "  -- no script loads the id that broke rendering --"
bad=0
for s in "$EF"/*.sh; do
  [ -f "$s" ] || continue
  if grep -nE '(load|unload)Effect[^a-zA-Z0-9]*macosglass([^0-9]|$)' "$s" >/dev/null 2>&1; then
    bad=$((bad+1)); printf '      -> %s usa el id viejo\n' "$(basename "$s")"
  fi
done
afirmar_igual "no script loads the old id" "0" "$bad"

echo "  -- the chain check before installing --"
# Without it, installing the .so leaves the screen black. Checking it directly is allowed,
# or delegating to verify-chain.sh (delegating is better: one source of truth).
for s in build.sh install.sh; do
  if grep -qE 'EffectsHandler::paintWindow|verify-chain\.sh' "$EF/$s" 2>/dev/null; then
    ok "$s checks the chain before installing"
  else
    fallo "$s does NOT check the chain before installing"
  fi
done

echo "  -- the grep pattern is deterministic --"
# grep -q exits on the first match and closes the pipe; under pipefail the result VARIES
# and can abort the installation of a correct .so. It happened twice.
bad=0
for s in "$EF"/*.sh; do
  [ -f "$s" ] || continue
  if grep -nE 'objdump.*\|[[:space:]]*grep[[:space:]]+-q' "$s" >/dev/null 2>&1; then
    bad=$((bad+1)); printf '      -> %s usa grep -q en un pipe\n' "$(basename "$s")"
  fi
done
afirmar_igual "no script uses 'grep -q' in a pipe" "0" "$bad"

echo "  -- self-sufficient: no binaries from build/ --"
# build/ is regenerable and is wiped on a rebuild, so a script that EXECUTES something from
# it breaks as soon as it is cleaned. (It happened.)
#
# This check was written against a variable name, `$HERE/build/`, that no script used: it
# matched nothing for its whole life, and a rename brought it back to life as a FALSE
# POSITIVE -- it flagged the screenshot directories `build/glass` and `build/titlebar`, which
# are not dependencies at all. What it checks now is the property: any path under build/ that
# a live script mentions is either the plugin (`.so`, regenerated by build.sh) or a directory
# the same script creates, never something it calls.
bad=$(python3 - "$EF" <<'PYEOF'
import glob, os, re, sys
bad = []
for ruta in sorted(glob.glob(os.path.join(sys.argv[1], "*.sh"))):
    for n, linea in enumerate(open(ruta, encoding="utf-8"), 1):
        if "/build/" not in linea or ".so" in linea:
            continue
        if "mkdir" in linea or re.match(r"\s*[A-Za-z_][A-Za-z0-9_]*=", linea):
            continue
        bad.append(f"{os.path.basename(ruta)}:{n}: {linea.strip()}")
for m in bad:
    print(f"      -> {m}")
print(len(bad))
PYEOF
)
afirmar_igual "no script executes anything from build/" "0" "${bad##*$'\n'}"

echo "  -- no live script waits for a journal tag that is gone --"
# The rot this catches: test-hot.sh and calibrate.sh waited for `CALIB` lines that the
# effect stopped emitting when M1.1's coordinate calibration was replaced, and nothing
# noticed for days -- a live script that cannot say anything looks exactly like a live
# script that has nothing to say. Both are in tests/archive/ now.
#
# The rule is narrow ON PURPOSE, and the first version was too wide: it took any ALL-CAPS
# word in single quotes, which matched a heredoc tag in build.sh and the words FOUND and NOT
# in verify-chain.sh, none of which are journal tags. What makes a word a tag is the LINE it
# is used in -- so only lines that actually read the journal count. It needs no allow-list,
# and a check with no allow-list is one nobody will quietly weaken.
missing=""
for s in "$EF"/*.sh; do
  [ -f "$s" ] || continue
  b="$(basename "$s")"
  # ONLY lines that read the journal, because a tag is defined by where it is used: widening
  # this to every grep line made it flag `WARNING` (an echo label) and `SOURCE`/`HEADER`
  # (verify-chain.sh's own variables), which are not tags of anything. BOTH quote styles, so
  # a real dependency written as grep -q "CALIB" is still caught.
  tags=$(grep -E 'journalctl' "$s" 2>/dev/null | grep -oE "['\"][^'\"]*['\"]" \
              | grep -oE '\b[A-Z][A-Z0-9_]{2,}\b' | sort -u)
  for e in $tags; do
    if ! codigo_contiene "$EF/src/glass.cpp" "$e"; then
      missing="$missing $b:$e"
    fi
  done
done
afirmar_igual "every journal tag a live script waits for still exists" "" "${missing# }"

echo "  -- tune.sh calls the command that actually reaches an effect --"
# The silent trap this project paid a whole session for: /KWin reconfigure re-parses kwinrc and
# never calls the effect's reconfigure(), so the value is written, the command reports success
# and the effect keeps its old one. tune.sh must call reconfigureEffect, and must NOT call the
# other, or it would be an automation of the bug.
afirmar_codigo "tune.sh uses reconfigureEffect" "$EF/tune.sh" 'Effects[.]reconfigureEffect'
negar "tune.sh does not use the command that silently does nothing" \
  codigo_contiene "$EF/tune.sh" 'KWin /KWin reconfigure'
afirmar_codigo "and it checks the keys against the source, so a typo is not silent" "$EF/tune.sh" 'readEntry'
afirmar_codigo "it applies once, after writing every key" "$EF/tune.sh" 'and only once'

echo "  -- capture-pair.sh takes both captures and puts the effect back --"
# The simulator is only usable if its two inputs exist, and producing them by hand is three tools
# and a guess about the rectangle. This script reads the rectangle from the effect's own journal,
# unloads the effect for the capture that must show the THEME, and reloads it through a trap --
# an interrupted run must not leave the user without their glass.
afirmar_codigo "the effect is unloaded for the theme's capture" "$EF/capture-pair.sh" 'unloadEffect'
afirmar_codigo "and loaded again" "$EF/capture-pair.sh" 'loadEffect'
afirmar_codigo "the trap restores it even on interrupt" "$EF/capture-pair.sh" 'trap restaurar EXIT INT TERM'
afirmar_codigo "both captures are cropped to the same strip" "$EF/capture-pair.sh" 'recorte = '

echo "  -- capture-pair.sh parses the geometry KWin reports --"
# The first version parsed the effect's journal line, which is STALE: the crop landed on a window
# that had moved, so "the theme's strip" was the desktop and the simulation still looked
# convincing. The geometry now comes from KWin's scripting for the ACTIVE window, in the same
# "x,y,w,h,bar" form test-titlebar.sh uses, and the parse is the same code the capture runs.
afirmar_igual "it reads the five numbers" "1226 476 1387 1138 38" \
  "$("$EF/capture-pair.sh" --geometry "1226,476,1387,1138,38" 2>/dev/null)"
afirmar_igual "a partly off-screen window keeps its negative x" "-120 40 800 600 34" \
  "$("$EF/capture-pair.sh" --geometry "-120.5,40.25,800,600,34" 2>/dev/null)"
afirmar_igual "and it is five FIELDS, because the capture does set --" "5" \
  "$("$EF/capture-pair.sh" --geometry "1226,476,1387,1138,38" 2>/dev/null | wc -w)"
# A window with no title bar (barHeight 0) must be refused, not cropped to nothing.
if "$EF/capture-pair.sh" --geometry "10,10,100,100,0" >/dev/null 2>&1; then
  fallo "a window with no title bar was accepted"
else
  ok "a window with no title bar is refused"
fi
# THE UNLOAD IS CHECKED, NOT ASSUMED: a capture with the effect on is its output, not its input.
afirmar_codigo "the unload is verified" "$EF/capture-pair.sh" 'isEffectLoaded'
afirmar_codigo "with a fallback that KWin does honour" "$EF/capture-pair.sh" '--group Plugins --key'
afirmar_codigo "and it refuses to capture if the effect is still loaded" "$EF/capture-pair.sh" 'a capture with the effect on is its OUTPUT'
afirmar_codigo "the geometry comes from the ACTIVE window, fresh" "$EF/capture-pair.sh" 'w[.]normalWindow && w[.]active'
afirmar_codigo "the trap puts the plugin key back too" "$EF/capture-pair.sh" 'PLUGIN_TOCADO'

echo "  -- tune.sh refuses a value that would break the material --"
# On 2026-10-14 the settings read GlassAlpha=40 BackgroundRadius=50 MaterialGain=15 Refraction=80
# RimWidth=90: the values I had suggested, each with its DECIMAL POINT LOST. GlassAlpha=40 makes the
# band `bar*40 - backdrop*39`, which is why the buttons and the title vanished, and nothing refused
# it. --validate checks without writing, so this test cannot damage the user's settings.
afirmar_igual "a sane alpha passes" "ok" "$("$EF/tune.sh" --validate GlassAlpha=0.15 2>&1 | tail -1)"
afirmar_igual "a lost decimal point is refused" "OUT OF RANGE: GlassAlpha=40" \
  "$("$EF/tune.sh" --validate GlassAlpha=40 2>&1 | tail -1)"
afirmar_igual "and so is its little brother" "OUT OF RANGE: GlassAlpha=15" \
  "$("$EF/tune.sh" --validate GlassAlpha=15 2>&1 | tail -1)"
# Every key has its own range, not one global one: a radius of 50 is odd but legal, a GAIN of 50 is not.
afirmar_igual "a large radius is still allowed" "ok" "$("$EF/tune.sh" --validate BackgroundRadius=50 2>&1 | tail -1)"
afirmar_igual "a gain of 15 is not" "OUT OF RANGE: MaterialGain=15" \
  "$("$EF/tune.sh" --validate MaterialGain=15 2>&1 | tail -1)"
afirmar_igual "nor a refraction of 80" "OUT OF RANGE: Refraction=80" \
  "$("$EF/tune.sh" --validate Refraction=80 2>&1 | tail -1)"
afirmar_igual "nor a band 90 pixels wide" "OUT OF RANGE: RimWidth=90" \
  "$("$EF/tune.sh" --validate RimWidth=90 2>&1 | tail -1)"
# A non-number is not a number either.
afirmar_igual "words are refused" "OUT OF RANGE: GlassAlpha=none" \
  "$("$EF/tune.sh" --validate GlassAlpha=none 2>&1 | tail -1)"
# And validation happens BEFORE anything is written: a good key next to a bad one changes nothing.
afirmar_codigo "all arguments are validated before any is written" "$EF/tune.sh" 'VALIDATE EVERYTHING FIRST'
