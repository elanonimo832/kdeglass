#!/usr/bin/env python3
# <analysis>
# generate-style-tracking.py — the macOS TRACKING table, from the token to the QStyle's C++.
#
# WHY THIS EXISTS (M6, slice 7). The macOS type scale's tracking is 64 of the 80 typography tokens,
# and `kdeglobals` has no field for it: the fonts M4 applies carry their size in POINTS (9.75 pt =
# 13 px at 96 dpi), and a QFont has no letter-spacing there. Qt DOES have one
# (`QFont::setLetterSpacing`), but only the style can reach it -- so this is the last thing that
# needed a home, and the style is that home.
#
# THE ONE DESIGN FACT THAT MAKES IT POSSIBLE. The token's `[tracking]` table is keyed by the TEXT
# SIZE, not by the role: 13 -> em1000 -6, 11 -> 6, 10 -> 12. So the style does NOT need to know
# whether it is drawing a menu item or a toolbar, which it cannot know; it needs the font's size,
# which it has. That is why this table is what gets generated, and not a role -> tracking map.
#
# THE UNITS, AND WHY THE CONVERSION LIVES IN ONE PLACE. `em1000` is the tracking in THOUSANDTHS OF AN
# EM (the CSS convention). In pixels at a size S the spacing is `em1000 / 1000 * S`, so the style
# multiplies by the font's PIXEL size and nothing else. The token also carries `puntos`, which is the
# same figure in points; it is NOT what the style uses -- one unit, one source, or the two drift.
#
# THE TABLE IS SPARSE ON PURPOSE. A dense array indexed by size would have to invent a value for
# every size the token does not publish, and a silent 0 there is a number nobody measured. The
# header carries one entry per published size; a lookup that misses returns 0 and means "leave the
# font alone".
# </analysis>
"""Emit style-kde-macos/src/tracking_table.h from tokens/tokens-typography_macos.toml.

    python3 tools/generate-style-tracking.py          # write the header
    python3 tools/generate-style-tracking.py --check  # exit 1 if the header is not current
"""

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKEN = ROOT / "tokens" / "tokens-typography_macos.toml"
HEADER = ROOT / "style-kde-macos" / "src" / "tracking_table.h"


def load():
    with open(TOKEN, "rb") as fh:
        data = tomllib.load(fh)
    # The TOML keys are the ASCII of the size ("6".."96"). Keep them as ints, in order.
    return {int(k): int(v["em1000"]) for k, v in data["tracking"].items()}


def render(table):
    sizes = sorted(table)
    entries = ",\n    ".join(f"{{{s}, {table[s]}}}" for s in sizes)
    first, last = sizes[0], sizes[-1]
    return f"""// style-kde-macos/src/tracking_table.h — GENERATED by tools/generate-style-tracking.py.
// DO NOT EDIT BY HAND; edit tokens/tokens-typography_macos.toml and regenerate.
//
// THE macOS TRACKING, keyed by TEXT SIZE. `em1000` is thousandths of an em (the CSS convention),
// so the pixel spacing at size S is `em1000 / 1000 * S`. The style multiplies by the font's PIXEL
// size; that is the whole conversion, and it is here rather than in the .cpp so the token and the
// code cannot disagree -- `tests/test-style-tracking.sh` regenerates and compares.
//
// SOURCE: tokens/tokens-typography_macos.toml [tracking], the table the HIG publishes. The token
// also carries `puntos` (the same figure in points); it is deliberately NOT used, because one unit
// in two places is how two numbers drift apart.
//
// ONE ENTRY PER PUBLISHED SIZE. A size the token does not publish is NOT in the table: filling a gap
// with 0 would be a number nobody measured, so the lookup returns 0 for a miss and the style leaves
// the font alone.
#pragma once

namespace kde_macos {{

struct TrackingEntry {{
    int size;    // the text size in px, which is the macOS point size (M4: 9.75 pt = 13 px at 96 dpi)
    int em1000;  // thousandths of an em; the pixel spacing is em1000 / 1000 * size
}};

// The sizes the HIG publishes: {first}..{last}.
constexpr TrackingEntry kTracking[] = {{
    {entries},
}};

// Thousandths of an em for a text size, or 0 when the HIG publishes none for it. 0 means "leave the
// font alone": it is the only safe answer for a size nobody measured, and it is what the miss
// returns instead of an invented value.
constexpr int trackingEm1000(int size)
{{
    for (const TrackingEntry &e : kTracking) {{
        if (e.size == size) {{
            return e.em1000;
        }}
    }}
    return 0;
}}

}} // namespace kde_macos
"""


def main(argv):
    if len(argv) > 1 and argv[1] not in ("--check",):
        print(__doc__.strip())
        return 2
    table = load()
    text = render(table)
    if len(argv) > 1 and argv[1] == "--check":
        if not HEADER.exists() or HEADER.read_text() != text:
            print("STALE: " + str(HEADER) + " does not match the token", file=sys.stderr)
            return 1
        print("current")
        return 0
    HEADER.write_text(text)
    print("wrote " + str(HEADER.relative_to(ROOT)) + " (" + str(len(table)) + " sizes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
